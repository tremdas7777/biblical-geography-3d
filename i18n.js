(function () {
  var LANG_KEY = 'bg3d_lang';

  function getNested(obj, path) {
    return path.split('.').reduce(function (o, k) { return o && o[k]; }, obj);
  }

  function detectLang() {
    var saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'es') return saved;
    return 'es';
  }

  window.getCurrentLang = detectLang;

  window.setLang = function (lang) {
    if (!window.I18N[lang]) return;
    localStorage.setItem(LANG_KEY, lang);
    applyLang(lang);
  };

  window.applyLang = function (lang) {
    var t = window.I18N[lang];
    if (!t) return;

    document.documentElement.lang = lang;

    var title = getNested(t, 'meta.title');
    var desc = getNested(t, 'meta.description');
    if (title) document.title = title;
    var metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && desc) metaDesc.setAttribute('content', desc);

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var val = getNested(t, el.getAttribute('data-i18n'));
      if (val != null) el.textContent = val;
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var val = getNested(t, el.getAttribute('data-i18n-html'));
      if (val != null) el.innerHTML = val;
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
      var val = getNested(t, el.getAttribute('data-i18n-alt'));
      if (val != null) el.setAttribute('alt', val);
    });

    document.querySelectorAll('[data-i18n-img]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-img');
      var src = getNested(t, 'images.' + key);
      if (src) el.setAttribute('src', src);
    });

    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      var isActive = btn.getAttribute('data-lang') === lang;
      btn.classList.toggle('active', isActive);
      btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
    });
  };

  applyLang(detectLang());
})();
